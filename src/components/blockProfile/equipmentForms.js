export const miscTypeLabel = (type) => MISC_TYPES.find((t) => t.value === type)?.label || type;

const pad = (value, length) => {
  const text = String(value ?? "").trim();
  return text ? text.padStart(length, "0") : "";
};

// SS (state LGD) + DDD (district LGD) + BBBB (block LGD); empty if a code is missing
export const assetPrefix = (geo = {}) => {
  const parts = [pad(geo.stateCode, 2), pad(geo.districtCode, 3), pad(geo.blockCode, 4)];
  return parts.every(Boolean) ? parts.join("") : "";
};

